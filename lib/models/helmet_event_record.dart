import 'dart:convert';

/// Categories of safety and IoT telemetry events logged by Smart Helmet 2.0.
enum HelmetEventType {
  accident,       // Crash impact, fall detection
  sos,            // Manual SOS distress signal
  helmetStatus,   // Helmet worn / removed transitions
  connection,     // ESP32 Wi-Fi connected / disconnected / reconnecting
  gpsUpdate,      // Significant coordinate waypoints & satellite fix changes
  alcoholLockout, // MQ-3 DUI interlock triggers
}

/// Severity classification for filtering and priority alerts.
enum EventSeverity {
  info,
  warning,
  critical,
  emergency,
}

/// Database record representing a persistent event in the blackbox SQLite log.
class HelmetEventRecord {
  final String id;
  final DateTime timestamp;
  final HelmetEventType eventType;
  final String title;
  final String description;
  final EventSeverity severity;
  final bool isDemo; // True if generated by Exhibition Demo Simulator, false if real ESP32
  final double? latitude;
  final double? longitude;
  final double? speedKmh;
  final double? alcoholPpm;
  final double? gForce;
  final String? status; // e.g. 'detected', 'delivered', 'safe', 'interlock_locked'
  final Map<String, dynamic>? metadata;

  const HelmetEventRecord({
    required this.id,
    required this.timestamp,
    required this.eventType,
    required this.title,
    required this.description,
    required this.severity,
    this.isDemo = false,
    this.latitude,
    this.longitude,
    this.speedKmh,
    this.alcoholPpm,
    this.gForce,
    this.status,
    this.metadata,
  });

  bool get hasCoordinates =>
      latitude != null &&
      longitude != null &&
      latitude != 0.0 &&
      longitude != 0.0;

  /// Serialization to SQLite Map
  Map<String, dynamic> toMap() {
    return {
      'id': id,
      'timestamp': timestamp.toIso8601String(),
      'event_type': eventType.name,
      'title': title,
      'description': description,
      'severity': severity.name,
      'is_demo': isDemo ? 1 : 0,
      'latitude': latitude,
      'longitude': longitude,
      'speed_kmh': speedKmh,
      'alcohol_ppm': alcoholPpm,
      'g_force': gForce,
      'status': status,
      'metadata': metadata != null ? jsonEncode(metadata) : null,
    };
  }

  /// Deserialization from SQLite Map
  factory HelmetEventRecord.fromMap(Map<String, dynamic> map) {
    Map<String, dynamic>? parsedMetadata;
    if (map['metadata'] != null) {
      try {
        if (map['metadata'] is String) {
          parsedMetadata = jsonDecode(map['metadata'] as String) as Map<String, dynamic>?;
        } else if (map['metadata'] is Map) {
          parsedMetadata = Map<String, dynamic>.from(map['metadata'] as Map);
        }
      } catch (_) {
        parsedMetadata = null;
      }
    }

    return HelmetEventRecord(
      id: map['id'] as String,
      timestamp: DateTime.tryParse(map['timestamp'] as String? ?? '') ?? DateTime.now(),
      eventType: HelmetEventType.values.firstWhere(
        (e) => e.name == map['event_type'],
        orElse: () => HelmetEventType.accident,
      ),
      title: map['title'] as String? ?? 'Safety Event',
      description: map['description'] as String? ?? '',
      severity: EventSeverity.values.firstWhere(
        (e) => e.name == map['severity'],
        orElse: () => EventSeverity.info,
      ),
      isDemo: (map['is_demo'] as int? ?? 0) == 1,
      latitude: (map['latitude'] as num?)?.toDouble(),
      longitude: (map['longitude'] as num?)?.toDouble(),
      speedKmh: (map['speed_kmh'] as num?)?.toDouble(),
      alcoholPpm: (map['alcohol_ppm'] as num?)?.toDouble(),
      gForce: (map['g_force'] as num?)?.toDouble(),
      status: map['status'] as String?,
      metadata: parsedMetadata,
    );
  }

  HelmetEventRecord copyWith({
    String? id,
    DateTime? timestamp,
    HelmetEventType? eventType,
    String? title,
    String? description,
    EventSeverity? severity,
    bool? isDemo,
    double? latitude,
    double? longitude,
    double? speedKmh,
    double? alcoholPpm,
    double? gForce,
    String? status,
    Map<String, dynamic>? metadata,
  }) {
    return HelmetEventRecord(
      id: id ?? this.id,
      timestamp: timestamp ?? this.timestamp,
      eventType: eventType ?? this.eventType,
      title: title ?? this.title,
      description: description ?? this.description,
      severity: severity ?? this.severity,
      isDemo: isDemo ?? this.isDemo,
      latitude: latitude ?? this.latitude,
      longitude: longitude ?? this.longitude,
      speedKmh: speedKmh ?? this.speedKmh,
      alcoholPpm: alcoholPpm ?? this.alcoholPpm,
      gForce: gForce ?? this.gForce,
      status: status ?? this.status,
      metadata: metadata ?? this.metadata,
    );
  }
}
